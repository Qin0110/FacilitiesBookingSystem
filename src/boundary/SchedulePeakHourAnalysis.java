    public SchedulePeakHourAnalysis(ScheduleControl scheduleControl) {
        this.scheduleControl = scheduleControl;
        initComponents();
        
        jTextArea1.setFont(new java.awt.Font("Courier New", 0, 16));
        
        jComboBox1.removeAllItems();
        jComboBox1.addItem("2025");
        jComboBox1.addItem("2026");
        
        jComboBox2.removeAllItems();
        String[] months = {"January", "February", "March", "April", "May", "June", 
                           "July", "August", "September", "October", "November", "December"};
        for (String m : months) {
            jComboBox2.addItem(m);
        }

        if (jComboBox1.getItemCount() > 0 && jComboBox2.getItemCount() > 0) {
            jComboBox1.setSelectedIndex(0);
            jComboBox2.setSelectedIndex(0); 
            updateReport(); 
        }
    }
    private void updateReport() {
        if (jComboBox1.getSelectedItem() != null && jComboBox2.getSelectedItem() != null) {
            
            int selectedYear = Integer.parseInt(jComboBox1.getSelectedItem().toString());
            int selectedMonth = jComboBox2.getSelectedIndex() + 1;
            String reportText = scheduleControl.monthlyFacilityPeakReport(selectedYear, selectedMonth);
            
            jTextArea1.setText(reportText);
            jTextArea1.setCaretPosition(0);
        }
    }

