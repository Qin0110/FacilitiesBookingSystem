    private void CancelBookingButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CancelBookingButtonActionPerformed
        String bookingId = bookingIDTF.getText();
        String studentId = studentIDTF.getText();
        String facilityName = facilityNameTF.getText();
        String scheduleSession = sessionTF.getText();
        String currentStatus = statusTF.getText();

        if (currentStatus.equals("Cancelled")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Already cancelled!");
            return;
        }

        String[] sessionDateTime = scheduleSession.split(" ", 2);
        String date = sessionDateTime[0];
        String session = sessionDateTime[1];

        int choice = javax.swing.JOptionPane.showConfirmDialog(this, "Cancel Booking " + bookingId + "?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        if (choice == javax.swing.JOptionPane.YES_OPTION) {
            entity.Booking targetBooking = bookingManager.getBookingById(bookingId);
            String facilityId;
            
            if (targetBooking != null) {
                facilityId = targetBooking.getSchedule().getFacility().getFacilityId();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: Could not locate original booking data.");
                return;
            }
            
            boolean success = bookingManager.cancelBooking(studentId, bookingId, facilityId, date, session);
            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, "Booking Cancelled. Schedule is now Available.");
                this.statusTF.setText("Cancelled"); 
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to cancel.");
            }
        }
    }//GEN-LAST:event_CancelBookingButtonActionPerformed

    private void DeleteBookingButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteBookingButtonActionPerformed
        String bookingId = bookingIDTF.getText();
        String status = statusTF.getText();

        if (status.equals("Confirmed")) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Warning: You must CANCEL this booking first to free up the room before deleting the record.",
                "Action Required", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int choice = javax.swing.JOptionPane.showConfirmDialog(this,
            "PERMANENTLY delete booking " + bookingId + "?", "Critical Warning", 
            javax.swing.JOptionPane.YES_NO_OPTION, javax.swing.JOptionPane.WARNING_MESSAGE);

        if (choice == javax.swing.JOptionPane.YES_OPTION) {
            if (bookingManager.removeBooking(bookingId)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Record wiped from database.");
                this.dispose(); 
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to delete record.");
            }
        }
    }//GEN-LAST:event_DeleteBookingButtonActionPerformed

    private void CheckInButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CheckInButtonActionPerformed
        String bookingId = bookingIDTF.getText();
        if (bookingManager.checkInStudent(bookingId)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Success! Student has been checked in.");
            this.statusTF.setText("In Progress"); 
            this.arrivalTimeTF.setText(java.time.LocalDateTime.now().format(java.time.format.DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm")));
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Check-In Failed.\n\n" +
                "1. The booking status must be 'Pending' or 'Confirmed'.\n" +
                "2. The current time must be within the valid check-in window (15 mins before/after start time).", 
                "Check-In Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_CheckInButtonActionPerformed

    private void CheckOutButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CheckOutButtonActionPerformed
        String bookingId = bookingIDTF.getText();
        if (bookingManager.checkOutStudent(bookingId)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Success! Student has been checked out.");
            this.statusTF.setText("Completed");
            this.leavingTimeTF.setText(java.time.LocalDateTime.now().format(java.time.format.DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm")));
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Check-Out Failed.\n\n" +
                "The student's booking must currently be 'In Progress' to perform a check-out.", 
                "Check-Out Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_CheckOutButtonActionPerformed


