    private void loadTableData(){
        //declare reference, =..... is like casting
        //e.g. Object obj = "hello"  -- here type is string but point to object
        //     String str = (String) obj  --change the object to string
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        adt.ListInterface<entity.Admin> admin = adminManager.getAllAdmins();
        
        for (int i = 0 ; i < admin.size() ; i++ ){
            entity.Admin s = admin.get(i);
            model.addRow(new Object[]{
                s.getAdminId(),
                s.getName(),
                s.getPosition(),
                s.getEmail(),
                s.getPhoneNumber()
            });
        }
    }
    
    private void loadTableData(String id){
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        Object selected = typeCB.getSelectedItem();
        String position = (selected != null) ? selected.toString() : "ALL";
        
        adt.ListInterface<entity.Admin> searchResults = adminManager.searchAdminForTable(id,position);
        
        for (int i = 0 ; i < searchResults.size() ; i++ ){
            entity.Admin s = searchResults.get(i);
            model.addRow(new Object[]{
                s.getAdminId(),
                s.getName(),
                s.getPosition(),
                s.getEmail(),
                s.getPhoneNumber()
            });
        }
        if (searchResults.size() == 0) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "No admin information found containing ID: " + id, 
            "Search Results", 
            javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
        
        
    }
    
    

